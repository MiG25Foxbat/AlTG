/**
 * Первый, самый дешёвый слой фильтрации: обычный поиск подстрок по теме,
 * без ИИ. Задача не в том, чтобы поймать всё (для русского языка с его
 * склонениями обычный substring почти всегда пропустит перефразированные
 * посты) — задача в том, чтобы бесплатно отсечь явно нерелевантное и
 * уменьшить объём текста, который дальше пойдёт в ИИ.
 * Если фильтр не находит вообще ничего — это ожидаемо и нормально:
 * analyzeService в этом случае отправляет в ИИ весь набор постов
 * (см. usedFallback в ответе API).
 */

const STOPWORDS = new Set([
  'и', 'в', 'во', 'не', 'что', 'он', 'на', 'я', 'с', 'со', 'как', 'а', 'то', 'все',
  'она', 'так', 'его', 'но', 'да', 'ты', 'к', 'у', 'же', 'вы', 'за', 'бы', 'по',
  'только', 'ее', 'мне', 'было', 'вот', 'от', 'меня', 'еще', 'нет', 'о', 'из',
  'ему', 'теперь', 'когда', 'даже', 'ну', 'вдруг', 'ли', 'если', 'уже', 'или',
  'ни', 'быть', 'был', 'него', 'до', 'вас', 'нибудь', 'опять', 'уж', 'вам',
  'сказал', 'для', 'про', 'этот', 'эта', 'это', 'эти', 'мой', 'моя', 'моё',
  'какой', 'какая', 'какие', 'кто', 'при', 'том', 'без', 'над', 'под',
]);

/** Разбивает тему на значимые слова: нижний регистр, только буквы/цифры, без стоп-слов и коротких обрубков. */
export function extractKeywords(topic: string): string[] {
  const words = topic
    .toLowerCase()
    .match(/[a-zа-яё0-9]+/gi);
  if (!words) return [];
  const unique = new Set(
    words.filter((w) => w.length >= 3 && !STOPWORDS.has(w))
  );
  return [...unique];
}

export interface FilterablePost {
  text: string;
}

/**
 * Возвращает посты, в которых буквально встречается хотя бы одно ключевое
 * слово (логика ИЛИ — она мягче и полезнее для теста, чем И, которое почти
 * всегда даст пустой результат).
 */
export function keywordPreFilter<T extends FilterablePost>(posts: T[], keywords: string[]): T[] {
  if (keywords.length === 0) return [];
  const lowerKeywords = keywords.map((k) => k.toLowerCase());
  return posts.filter((post) => {
    const lowerText = post.text.toLowerCase();
    return lowerKeywords.some((kw) => lowerText.includes(kw));
  });
}
